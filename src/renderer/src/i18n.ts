const DICTIONARIES: Record<Language, Record<TranslationKey, string>> = { fr, en }

/** Étiquette de chaque langue, toujours écrite dans sa propre langue. */
export const LANGUAGE_LABEL: Record<Language, string> = {
  fr: 'Français',
  en: 'English'
}

/** Locale BCP 47 pour les formats de date et de nombre. */
export const LOCALE: Record<Language, string> = {
  fr: 'fr-FR',
  en: 'en-GB'
}

export function resolveLanguage(choice: string): Language {
  if (choice === 'fr' || choice === 'en') return choice
  return navigator.language.toLowerCase().startsWith('fr') ? 'fr' : 'en'
}

export function translate(
  language: Language,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const template = DICTIONARIES[language][key]
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match
  )
}
